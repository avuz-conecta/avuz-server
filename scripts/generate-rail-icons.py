def render_script(glyphs: dict) -> str:
    payload = {
        "viewBox": VIEW_BOX,
        "apps": GLYPH_BY_APP,
        "rail": RAIL_GLYPHS,
        "glyphs": glyphs,
    }
    return (
        "/**\n"
        f" * Material Symbols ({STYLE.capitalize()}, weight {WEIGHT}) {VERSION}, Apache License 2.0\n"
        " * (material-icons.LICENSE). Generated by scripts/generate-rail-icons.py; do not edit.\n"
        " *\n"
        " * window.AvuzIcons: apps maps an app id to a glyph name, rail names the rail's own\n"
        " * controls, glyphs holds each glyph's path data (regular and fill) on viewBox.\n"
        " */\n"
        f"window.AvuzIcons = Object.freeze({json.dumps(payload, indent='\t', ensure_ascii=False)});\n"
    )


def main() -> int:
    names = sorted(set(GLYPH_BY_APP.values()) | set(RAIL_GLYPHS.values()) | {name for name, _, _ in ICON_FILES})
    glyphs = {name: {"regular": glyph_path(name), "fill": glyph_path(f"{name}-fill")} for name in names}

    SCRIPT_OUTPUT.write_text(render_script(glyphs), encoding="utf-8")
    LICENSE_OUTPUT.write_text(download("LICENSE"), encoding="utf-8")
    for name, relative_path, fill in ICON_FILES:
        (REPO_ROOT / relative_path).parent.mkdir(parents=True, exist_ok=True)
        (REPO_ROOT / relative_path).write_text(render_svg(glyphs[name]["regular"], fill), encoding="utf-8")

    print(f"wrote {len(glyphs)} glyphs ({PACKAGE}@{VERSION} {STYLE}) and {len(ICON_FILES)} icon files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
