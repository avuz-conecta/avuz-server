#!/usr/bin/env python3
"""Generate the app icons from Material Symbols (Rounded, weight 200).

Downloads each glyph, plain and filled, from the pinned npm package through
jsDelivr and writes:
  apps/avuz_theme/js/material-icons.js   window.AvuzIcons, read by the left rail
                                         and the favicon (classic script, so it
                                         rides the server's ?v= cache buster)
  themes/avuz/apps/<app>/img/*.svg       the theme's app icon overrides: light
                                         fill="currentColor", dark fill="#000000"
  apps/conectamail/img/mail.svg          ConectaMail's own app icon
  apps/avuz_theme/js/material-icons.LICENSE

Design: docs/superpowers/specs/2026-10-23-rail-material-icons-design.md
Usage: python3 -I scripts/generate-rail-icons.py
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PACKAGE = "@material-symbols/svg-200"
VERSION = "0.48.1"
STYLE = "rounded"
PACKAGE_URL = f"https://cdn.jsdelivr.net/npm/{PACKAGE}@{VERSION}"
VIEW_BOX = "0 -960 960 960"

SCRIPT_OUTPUT = REPO_ROOT / "apps/avuz_theme/js/material-icons.js"
LICENSE_OUTPUT = REPO_ROOT / "apps/avuz_theme/js/material-icons.LICENSE"
THEME_APPS = REPO_ROOT / "themes/avuz/apps"

GLYPH_BY_APP = {
    "dashboard": "space_dashboard",
    "files": "folder",
    "spreed": "chat_bubble",
    "calendar": "calendar_today",
    "deck": "view_kanban",
    "contacts": "group",
    "mail": "mail",
    "conectamail": "mail",
    "forms": "list_alt",
    "activity": "bolt",
    "assinaturas": "signature",
    "settings": "settings",
}
RAIL_GLYPHS = {
    "collapse": "keyboard_double_arrow_left",
    "expand": "keyboard_double_arrow_right",
    "more": "more_horiz",
}

LIGHT_FILL = "currentColor"
DARK_FILL = "#000000"
# (glyph, path relative to the repo, fill)
ICON_FILES = [
    ("bolt", "themes/avuz/apps/activity/img/activity.svg", LIGHT_FILL),
    ("bolt", "themes/avuz/apps/activity/img/activity-dark.svg", DARK_FILL),
    ("signature", "themes/avuz/apps/assinaturas/img/app.svg", LIGHT_FILL),
    ("signature", "themes/avuz/apps/assinaturas/img/app-dark.svg", DARK_FILL),
    ("calendar_today", "themes/avuz/apps/calendar/img/calendar.svg", LIGHT_FILL),
    ("calendar_today", "themes/avuz/apps/calendar/img/calendar-dark.svg", DARK_FILL),
    ("group", "themes/avuz/apps/contacts/img/app.svg", LIGHT_FILL),
    ("space_dashboard", "themes/avuz/apps/dashboard/img/dashboard.svg", LIGHT_FILL),
    ("view_kanban", "themes/avuz/apps/deck/img/deck.svg", LIGHT_FILL),
    ("view_kanban", "themes/avuz/apps/deck/img/deck-dark.svg", DARK_FILL),
    ("folder", "themes/avuz/apps/files/img/app.svg", LIGHT_FILL),
    ("folder", "themes/avuz/apps/files/img/app-dark.svg", DARK_FILL),
    ("list_alt", "themes/avuz/apps/forms/img/forms.svg", LIGHT_FILL),
    ("list_alt", "themes/avuz/apps/forms/img/forms-dark.svg", DARK_FILL),
    ("mail", "themes/avuz/apps/mail/img/mail.svg", LIGHT_FILL),
    ("mail", "themes/avuz/apps/mail/img/mail-dark.svg", DARK_FILL),
    ("settings", "themes/avuz/apps/settings/img/app.svg", LIGHT_FILL),
    ("chat_bubble", "themes/avuz/apps/spreed/img/app.svg", LIGHT_FILL),
    ("chat_bubble", "themes/avuz/apps/spreed/img/app-dark.svg", DARK_FILL),
    ("mail", "apps/conectamail/img/mail.svg", LIGHT_FILL),
]

SINGLE_PATH = re.compile(r'^<svg[^>]*viewBox="0 -960 960 960"[^>]*><path d="([^"]+)"/></svg>$')


def download(path: str) -> str:
    with urllib.request.urlopen(f"{PACKAGE_URL}/{path}", timeout=30) as response:
        return response.read().decode("utf-8")


def glyph_path(file_name: str) -> str:
    source = download(f"{STYLE}/{file_name}.svg").strip()
    match = SINGLE_PATH.match(source)
    if match is None:
        raise ValueError(f"{file_name}: expected one <path> on a {VIEW_BOX} viewBox, got {source[:120]}")
    return match.group(1)


def render_svg(path_data: str, fill: str) -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="{VIEW_BOX}" fill="{fill}">\n'
        f'  <path d="{path_data}"/>\n'
        "</svg>\n"
    )


def render_script(glyphs: dict) -> str:
    payload = {
        "viewBox": VIEW_BOX,
        "apps": GLYPH_BY_APP,
        "rail": RAIL_GLYPHS,
        "glyphs": glyphs,
    }
    return (
        "/**\n"
        f" * Material Symbols ({STYLE.capitalize()}, weight 200) {VERSION}, Apache License 2.0\n"
        " * (material-icons.LICENSE). Generated by scripts/generate-rail-icons.py; do not edit.\n"
        " *\n"
        " * window.AvuzIcons: apps maps an app id to a glyph name, rail names the rail's own\n"
        " * controls, glyphs holds each glyph's path data (regular and fill) on viewBox.\n"
        " */\n"
        f"window.AvuzIcons = Object.freeze({json.dumps(payload, indent='\t', ensure_ascii=False)});\n"
    )


def main() -> int:
    names = sorted(set(GLYPH_BY_APP.values()) | set(RAIL_GLYPHS.values()))
    glyphs = {name: {"regular": glyph_path(name), "fill": glyph_path(f"{name}-fill")} for name in names}

    SCRIPT_OUTPUT.write_text(render_script(glyphs), encoding="utf-8")
    LICENSE_OUTPUT.write_text(download("LICENSE"), encoding="utf-8")
    for name, relative_path, fill in ICON_FILES:
        (REPO_ROOT / relative_path).write_text(render_svg(glyphs[name]["regular"], fill), encoding="utf-8")

    print(f"wrote {len(glyphs)} glyphs ({PACKAGE}@{VERSION} {STYLE}) and {len(ICON_FILES)} icon files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
